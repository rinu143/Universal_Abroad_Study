          <?php
          // List of countries and their respective classes
          $countries = [
            "lithuania" => "university-lithuania",
            "georgia" => "university-georgia",
            "ireland" => "university-ireland",
            "hungary" => "university-hungary",
            "czech" => "university-czech",
            "slovakia" => "university-slovakia",
            "estonia" => "university-estonia",
            "malta" => "university-malta",
            "france" => "university-france",
            "latvia" => "university-latvia",
            "uk" => "university-uk",
            "sweden" => "university-sweden",
            "poland" => "university-poland",
            // Add other countries here
          ];

          // Get the selected country from the URL parameter
          $selectedCountry = isset($_GET['country']) ? strtolower($_GET['country']) : null;

          // Check if the selected country is in the array
          if ($selectedCountry && array_key_exists($selectedCountry, $countries)) {
            $countryClass = $countries[$selectedCountry];
            
            // Load the contents of university.html
            $universityHtml = file_get_contents('university.html');

            // Use DOMDocument to parse the HTML
            $dom = new DOMDocument();
            libxml_use_internal_errors(true); // Ignore HTML parsing errors
            $dom->loadHTML($universityHtml);
            libxml_clear_errors();

            // Find the relevant university section by class
            $xpath = new DOMXPath($dom);
            $query = "//*[contains(@class, '$countryClass')]";
            $entries = $xpath->query($query);

            // Display the section if found
            if ($entries->length > 0) {
              foreach ($entries as $entry) {
                echo $dom->saveHTML($entry);
              }
            } else {
              echo "<p style='text-align:center; font-size: 1.1rem; color:red;font-weight: 700;'>No universities found for the selected country.</p>";
            }
          } else {
            echo "<p style='text-align:center; font-size: 1.1rem; color:red;font-weight: 700;'>Please select a valid country.</p>";
          }
          ?>
        </section>


